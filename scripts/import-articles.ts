/* cross-article validation */
const slugs = new Map<string, string>();
for (const item of parsed) {
  const other = slugs.get(item.article.slug);
  if (other) throw new Error(`slug "${item.article.slug}" is used by both ${other} and ${item.file}`);
  slugs.set(item.article.slug, item.file);
}
const slugSet = new Set(slugs.keys());

/* resolve every inline link now that the full slug set is known */
const restored: Record<Restored, number> = { article: 0, page: 0, external: 0 };
const droppedTargets: string[] = [];
for (const item of parsed) {
  for (const rich of proseOf(item.article)) {
    if (!rich.links) continue;
    const kept: LinkMark[] = [];
    for (const mark of rich.links) {
      const resolved = resolveHref(mark.href, slugSet);
      if (resolved === null) {
        droppedTargets.push(mark.href);
      } else {
        restored[resolved.outcome] += 1;
        kept.push({ ...mark, href: resolved.href });
      }
    }
    if (kept.length > 0) rich.links = kept;
    else delete rich.links;
    checkMarks(rich, item.file);
  }
}

for (const item of parsed) {
  for (const slug of item.article.related) {
    if (!slugSet.has(slug)) throw new Error(`${item.file}: related article "${slug}" was not imported`);
    if (slug === item.article.slug) throw new Error(`${item.file}: relates to itself`);
  }
  for (const source of item.article.sources) {
    if (!/^https:\/\/[^\s/]+/.test(source.url)) {
      throw new Error(`${item.file}: source "${source.name}" has a non-https URL: ${source.url}`);
    }
  }
  const strings = everyString(item.article);
  const offenders = strings.filter(
    (text) => /\[[A-Z]/.test(text) || /not for publication/i.test(text) || /TalentRax/.test(text),
  );
  if (offenders.length > 0) {
    throw new Error(`${item.file}: placeholder or unpublishable text survived:\n  ${offenders.join("\n  ")}`);
  }
}

