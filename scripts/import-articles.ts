/**
 * import-articles.ts - import the client's .docx articles into
 * src/content/articles/, one typed file per article plus an index.
 *
 *   node scripts/import-articles.ts <directory-of-docx> [--date YYYY-MM-DD]
 *   npm run import:articles -- <directory-of-docx>
 *
 * The parser, not a transcription. Thirty articles copied by hand would
 * drift from the source in thirty small ways; this reads the .docx XML
 * directly and emits the content, so a re-import is repeatable and a diff
 * against the previous import is meaningful. Node's own zlib inflates the
 * .docx (it is a zip), so there is no dependency to install.
 *
 * WHAT COUNTS AS AN ARTICLE. A document with a "SEO and optimization notes"
 * section. Anything else in the directory (the strategy documents and the
 * monthly optimization audits) is internal planning material: it is skipped,
 * reported, and never written anywhere.
 *
 * WHAT IS STRIPPED, so it can never reach the site:
 *   - the whole "SEO and optimization notes (not for publication)" section,
 *     including the quality-control and confirm-before-publishing tables.
 *     Three fields are read out of it first (SEO title, meta description and
 *     the URL, which supplies the slug) and the rest is discarded;
 *   - the byline placeholder "By [Author name], [Title], ...". No named
 *     people anywhere on this site, and no bracketed placeholders;
 *   - the "Related reading" / "Learn more" / closing call-to-action
 *     sections, which are link lists. Links to other imported articles are
 *     kept as `related` slugs; the call-to-action prose in them is dropped
 *     and reported.
 *
 * INLINE LINKS are carried as marks on the prose: a paragraph, list item or
 * FAQ answer is `{ text, links: [{ start, end, href }] }`, offsets into the
 * text. Every href is resolved before it is written:
 *   - a link to an imported article becomes `/insights/<slug>`;
 *   - a link to a page this site has (a `src/app/<path>/page.tsx` exists)
 *     becomes that path;
 *   - an https link elsewhere is kept as it is;
 *   - anything else (the documents link to pages that were never built)
 *     keeps its text and loses the link, and the target is reported.
 * Links inside table cells and the takeaways box are dropped and counted:
 * cells are plain strings.
 *
 * WHAT IS PRESERVED EXACTLY: every figure and every attribution. The
 * site-wide no-statistics rule bans invented claims about Talentrax's own
 * performance; the cited third-party data in these articles is their whole
 * value. Nothing here rounds, restates or drops a number, and every source
 * comes through with its URL.
 *
 * BRAND. The documents spell the name "TalentRax". The site is "Talentrax"
 * (see CLAUDE.md) and the fix is applied to every string on the way out.
 *
 * DATES. The documents carry "Last updated: <Month> <Year>", and most of
 * those months are in the future relative to the import. A BlogPosting with
 * a future datePublished is wrong, so a future month is never imported:
 * the article gets the import date instead and is listed in the report. A
 * month already in the past becomes the first of that month. Once an
 * article has been written to src/content/articles/, its datePublished is
 * preserved across re-imports and its dateModified moves only when its
 * content changes.
 *
 * The script fails loudly, with the file name, on anything it does not
 * recognise: a heading level it has not seen, a list item outside a list,
 * a missing takeaways table. Silent tolerance is how a stripped section
 * comes back.
 */

