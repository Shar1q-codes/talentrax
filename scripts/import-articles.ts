for (const item of parsed.sort((a, b) => a.article.slug.localeCompare(b.article.slug))) {
  const { slug } = item.article;
  const path = join(OUTPUT_DIR, `${slug}.ts`);
  const { year, month } = item.statedDate;

  let sourceDate: string;
  if (year > importYear || (year === importYear && month > importMonth)) {
    futureDated.push({ slug, stated: item.statedDate.text });
    sourceDate = importDate;
  } else if (year === importYear && month === importMonth) {
    sourceDate = importDate;
  } else {
    sourceDate = `${year}-${String(month).padStart(2, "0")}-01`;
  }

  const existing = existingDates(path);
  let article: Article = {
    id: slug,
    ...item.article,
    datePublished: existing?.datePublished ?? sourceDate,
    dateModified: existing?.dateModified ?? sourceDate,
  };
  let text = articleFile(article, item.file);
  if (existing && readFileSync(path, "utf8") !== text) {
    article = { ...article, dateModified: importDate };
    text = articleFile(article, item.file);
  }
  writeFileSync(path, text);
  written.add(`${slug}.ts`);
}

